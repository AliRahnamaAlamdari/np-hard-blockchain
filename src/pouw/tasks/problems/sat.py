"""3-SAT as a decision :class:`ProblemClass`.

A satisfiable 3-CNF instance is generated by planting a random assignment and only
emitting clauses it satisfies, so a witness always exists (the useful-work layer needs
solvable instances). The miner's exact solver is exhaustive search over all ``2^N``
assignments; the reference solver is DPLL with unit propagation, which decides the same
instance far faster.

This is the one *decision* class in the suite, included to show the framework is not
tied to optimization problems. The "cost" is the number of satisfied clauses (negated,
so lower is better and an optimum corresponds to all clauses satisfied); verification is
``O(clauses)`` -- evaluate the CNF under the witness assignment.
"""

from __future__ import annotations

import random
from typing import Any

from .base import ProblemClass, ProblemInstance, Solution, register


class SATProblem(ProblemClass):
    name = "sat"
    exact_complexity = "O(2^N)"  # exhaustive assignment search
    verify_complexity = "O(M)"  # M clauses
    is_decision = True
    constraint_rejects_random = True

    def generate(self, instance_id, size, seed, clause_ratio=4.0, **params):
        rng = random.Random(seed)
        n = size
        planted = [rng.random() < 0.5 for _ in range(n)]
        num_clauses = max(1, int(clause_ratio * n))
        clauses: list[list[int]] = []
        attempts = 0
        while len(clauses) < num_clauses and attempts < num_clauses * 50:
            attempts += 1
            vars_ = rng.sample(range(n), 3) if n >= 3 else [rng.randrange(n) for _ in range(3)]
            # literal encoded as (var+1) positive, -(var+1) negative
            clause = []
            for var in vars_:
                negate = rng.random() < 0.5
                clause.append(-(var + 1) if negate else (var + 1))
            # keep only clauses satisfied by the planted assignment
            if any((lit > 0) == planted[abs(lit) - 1] for lit in clause):
                clauses.append(clause)
        return ProblemInstance(
            instance_id=instance_id,
            problem_class=self.name,
            size=n,
            data={"num_vars": n, "clauses": clauses},
            metadata={"seed": seed, "clause_ratio": clause_ratio},
        )

    @staticmethod
    def _satisfied(clauses, assignment) -> int:
        count = 0
        for clause in clauses:
            for lit in clause:
                if (lit > 0) == assignment[abs(lit) - 1]:
                    count += 1
                    break
        return count

    def solve_exact(self, instance):
        n = instance.data["num_vars"]
        clauses = instance.data["clauses"]
        best_assignment = [False] * n
        best_sat = -1
        ops = 0
        for mask in range(1 << n):
            ops += 1
            assignment = [(mask >> i) & 1 == 1 for i in range(n)]
            sat = self._satisfied(clauses, assignment)
            if sat > best_sat:
                best_sat = sat
                best_assignment = assignment
                if sat == len(clauses):
                    break
        return Solution(self.name, [bool(b) for b in best_assignment], float(-best_sat), feasible=True), ops

    def solve_reference(self, instance):
        """DPLL with unit propagation; decides satisfiability quickly."""
        n = instance.data["num_vars"]
        clauses = [list(c) for c in instance.data["clauses"]]
        assignment: dict[int, bool] = {}
        ops = [0]

        def dpll(clauses, assignment):
            ops[0] += 1
            # unit propagation
            assignment = dict(assignment)
            changed = True
            while changed:
                changed = False
                for clause in clauses:
                    unassigned = [lit for lit in clause if abs(lit) not in assignment]
                    satisfied = any(
                        abs(lit) in assignment and (lit > 0) == assignment[abs(lit)]
                        for lit in clause
                    )
                    if satisfied:
                        continue
                    if not unassigned:
                        return None  # conflict
                    if len(unassigned) == 1:
                        lit = unassigned[0]
                        assignment[abs(lit)] = lit > 0
                        changed = True
            if len(assignment) == n:
                return assignment
            var = next(v for v in range(1, n + 1) if v not in assignment)
            for value in (True, False):
                trial = dict(assignment)
                trial[var] = value
                result = dpll(clauses, trial)
                if result is not None:
                    return result
            return None

        result = dpll(clauses, assignment)
        if result is None:
            full = [False] * n
        else:
            full = [result.get(i + 1, False) for i in range(n)]
        sat = self._satisfied(clauses, full)
        return Solution(self.name, [bool(b) for b in full], float(-sat), feasible=True), ops[0]

    def verify(self, instance, solution, quality_threshold=None, reference_cost=None, cost_tolerance=1e-9):
        n = instance.data["num_vars"]
        clauses = instance.data["clauses"]
        assignment = solution.witness
        if not isinstance(assignment, list) or len(assignment) != n:
            return False, "malformed_witness"
        assignment = [bool(b) for b in assignment]
        sat = self._satisfied(clauses, assignment)
        if abs(float(-sat) - solution.cost) > cost_tolerance:
            return False, "sat_count_mismatch"
        # For a planted-satisfiable instance the optimum satisfies all clauses.
        if quality_threshold is None:
            if sat < len(clauses):
                return False, "not_all_clauses_satisfied"
        else:
            required = len(clauses) * (1.0 - quality_threshold)
            if sat < required - cost_tolerance:
                return False, "quality_threshold_not_met"
        return True, "ok"

    def random_witness(self, instance, rng):
        n = instance.data["num_vars"]
        assignment = [rng.random() < 0.5 for _ in range(n)]
        sat = self._satisfied(instance.data["clauses"], assignment)
        return Solution(self.name, [bool(b) for b in assignment], float(-sat), feasible=True)


register(SATProblem())
